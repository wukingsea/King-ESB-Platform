-- King ESB Platform — initial schema.
-- Portable across PostgreSQL (production) and H2 (dev/test).

CREATE TABLE esb_route (
    id          VARCHAR(64)   NOT NULL,
    name        VARCHAR(255)  NOT NULL,
    description VARCHAR(1000),
    path        VARCHAR(512)  NOT NULL,
    method      VARCHAR(16)   NOT NULL,
    priority    INTEGER       NOT NULL,
    enabled     BOOLEAN       NOT NULL,
    api_key     VARCHAR(255),
    config_json TEXT          NOT NULL,
    version     INTEGER       NOT NULL,
    created_by  VARCHAR(128),
    created_at  TIMESTAMP,
    updated_by  VARCHAR(128),
    updated_at  TIMESTAMP,
    CONSTRAINT pk_esb_route PRIMARY KEY (id),
    CONSTRAINT uq_esb_route_name UNIQUE (name)
);

CREATE TABLE esb_call_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    trace_id      VARCHAR(64),
    route_id      VARCHAR(64),
    method        VARCHAR(16),
    path          VARCHAR(512),
    status        VARCHAR(32),
    http_status   INTEGER,
    duration_ms   BIGINT,
    client_ip     VARCHAR(64),
    error_code    VARCHAR(64),
    error_message VARCHAR(2000),
    created_at    TIMESTAMP,
    CONSTRAINT pk_esb_call_log PRIMARY KEY (id)
);

CREATE INDEX idx_call_log_route ON esb_call_log (route_id);
CREATE INDEX idx_call_log_created ON esb_call_log (created_at);

CREATE TABLE esb_user (
    id            VARCHAR(64)  NOT NULL,
    username      VARCHAR(128) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    roles         VARCHAR(255) NOT NULL,
    enabled       BOOLEAN      NOT NULL,
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT pk_esb_user PRIMARY KEY (id),
    CONSTRAINT uq_esb_user_username UNIQUE (username)
);

CREATE TABLE esb_audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor      VARCHAR(128),
    action     VARCHAR(64),
    target     VARCHAR(255),
    detail     VARCHAR(2000),
    created_at TIMESTAMP,
    CONSTRAINT pk_esb_audit_log PRIMARY KEY (id)
);
